export function useCategoryLabel() {
  const { t } = useI18n();
  return (cat: string) => categoryKeyMap[cat] ? t(categoryKeyMap[cat]) : cat;
}

export function useDayLabel() {
  const { t } = useI18n();
  return (day: string) => dayKeyMap[day.toLowerCase()] ? t(dayKeyMap[day.toLowerCase()]) : day;
}
